import React, { useState, useEffect } from 'react';
import axios from 'axios';

export default function TransactionHistory() {
  const [transactions, setTransactions] = useState([]);

  const printReceipt = (t) => {
    const printWindow = window.open('', '', 'width=900,height=1100');
    if (!printWindow) return;

    const receiptNumber = `RCPT-${t.id}`;
    const html = `
      <!DOCTYPE html>
      <html>
      <head>
        <title>Payment Receipt - ${t.student_name || 'Student'}</title>
        <style>
          body { font-family: Arial, sans-serif; margin: 24px; color: #0f172a; }
          .card { max-width: 700px; margin: 0 auto; border: 1px solid #cbd5e1; border-radius: 12px; overflow: hidden; }
          .header { background: #1e40af; color: white; padding: 20px; }
          .title { font-size: 22px; font-weight: 800; }
          .sub { font-size: 12px; opacity: 0.9; margin-top: 4px; }
          .body { padding: 20px; }
          .row { display: flex; justify-content: space-between; padding: 10px 0; border-bottom: 1px solid #e2e8f0; }
          .label { color: #475569; font-weight: 600; }
          .value { font-weight: 700; }
          .amount { font-size: 28px; color: #0f766e; font-weight: 900; }
          .footer { padding: 16px 20px; font-size: 12px; color: #64748b; }
          @media print { button { display: none; } body { margin: 0; } }
        </style>
      </head>
      <body>
        <div class="card">
          <div class="header">
            <div class="title">🧾 Payment Receipt</div>
            <div class="sub">Generated by EduPulse</div>
          </div>
          <div class="body">
            <div class="row"><span class="label">Receipt Number</span><span class="value">${receiptNumber}</span></div>
            <div class="row"><span class="label">Date</span><span class="value">${t.date || '-'}</span></div>
            <div class="row"><span class="label">Student</span><span class="value">${t.student_name || '-'}</span></div>
            <div class="row"><span class="label">Payment Type</span><span class="value">${t.type || '-'}</span></div>
            <div class="row"><span class="label">Method</span><span class="value">${t.method || '-'}</span></div>
            <div class="row"><span class="label">Status</span><span class="value">${t.status || '-'}</span></div>
            <div class="row" style="border-bottom: none; margin-top: 8px;"><span class="label">Amount</span><span class="amount">GH₵ ${t.amount || '0.00'}</span></div>
          </div>
          <div class="footer">Generated on ${new Date().toLocaleString()} • Keep this receipt for records.</div>
        </div>
        <button onclick="window.print()" style="display:block;margin:20px auto;padding:10px 24px;background:#1e40af;color:white;border:none;border-radius:8px;cursor:pointer;font-weight:700;">Print Receipt</button>
      </body>
      </html>
    `;

    printWindow.document.write(html);
    printWindow.document.close();
    printWindow.focus();
    setTimeout(() => printWindow.print(), 400);
  };

  useEffect(() => {
    const fetchTransactions = async () => {
      const headers = { 
        'Authorization': `Bearer ${localStorage.getItem('token')}`,
        'X-School-ID': localStorage.getItem('school_id') 
      };
      const res = await axios.get('/api/finance/transactions', { headers });
      setTransactions(res.data);
    };
    fetchTransactions();
  }, []);

  const downloadCSV = () => {
    if (!transactions.length) return alert("No transactions to export.");

    const headers = ["Date", "Student Name", "Type", "Method", "Amount", "Status"];
    const rows = transactions.map(t => [
      t.date,
      `"${t.student_name}"`,
      t.type,
      t.method,
      t.amount,
      t.status
    ]);

    const csvContent = [
      headers.join(','),
      ...rows.map(r => r.join(','))
    ].join('\n');

    const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.setAttribute('download', `financial_ledger_${new Date().toISOString().split('T')[0]}.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  return (
    <div className="bg-white p-8 rounded-3xl shadow-sm border border-slate-100">
      <div className="flex justify-between items-center mb-6">
        <h2 className="text-2xl font-bold text-slate-800">Financial Ledger</h2>
        <button onClick={downloadCSV} className="bg-green-600 text-white px-4 py-2 rounded-xl font-bold hover:bg-green-700 shadow-lg shadow-green-200 flex items-center gap-2">
          📥 Export CSV
        </button>
      </div>
      <div className="overflow-x-auto">
        <table className="w-full text-left">
          <thead className="bg-slate-50 border-b">
            <tr className="text-slate-500 text-xs font-bold uppercase">
              <th className="p-4">Date</th>
              <th className="p-4">Student</th>
              <th className="p-4">Type</th>
              <th className="p-4">Method</th>
              <th className="p-4">Amount</th>
              <th className="p-4">Status</th>
              <th className="p-4">Receipt</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-slate-100">
            {transactions.map(t => (
              <tr key={t.id} className="hover:bg-slate-50">
                <td className="p-4 text-sm text-slate-600">{t.date}</td>
                <td className="p-4 font-bold text-slate-800">{t.student_name}</td>
                <td className="p-4 text-sm">{t.type}</td>
                <td className="p-4 text-sm">{t.method}</td>
                <td className="p-4 font-mono font-bold text-green-600">GH₵ {t.amount}</td>
                <td className="p-4"><span className={`px-2 py-1 rounded text-xs font-bold ${t.status === 'Confirmed' ? 'bg-green-100 text-green-700' : 'bg-yellow-100 text-yellow-700'}`}>{t.status}</span></td>
                <td className="p-4">
                  <button
                    onClick={() => printReceipt(t)}
                    className="px-3 py-1 bg-blue-100 text-blue-700 rounded text-xs font-bold hover:bg-blue-200"
                    title="Print payment receipt"
                  >
                    🧾 Print
                  </button>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
}